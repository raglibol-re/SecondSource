import { readFileSync, writeFileSync } from 'node:fs';

// Writes the deployed GuardedVault address and ABI into src/vault/deployment.generated.ts, so the website's functions
// can call the contract without the Foundry build output. Run after every deployment.
const dep = JSON.parse(readFileSync('contracts/deployments.json', 'utf8')).baseSepolia;
const { abi } = JSON.parse(readFileSync('contracts/out/GuardedVault.sol/GuardedVault.json', 'utf8'));
const stale = JSON.parse(readFileSync('contracts/test/fixtures/nodary-eth-usd.json', 'utf8'));
writeFileSync(
  'src/vault/deployment.generated.ts',
  `// Generated by src/scripts/vault-export.ts from contracts/deployments.json and the Foundry build. Do not edit.\n` +
    `export const VAULT_ADDRESS = ${JSON.stringify(dep.GuardedVault)} as const;\n` +
    `export const VAULT_DEPLOY_TX = ${JSON.stringify(dep.deployTx)} as const;\n` +
    `export const VAULT_ABI = ${JSON.stringify(abi)} as const;\n` +
    `// A real Nodary ETH/USD response signed long ago, for the "too old" tamper case.\n` +
    `export const STALE_ETH_USD = ${JSON.stringify(stale)} as const;\n`
);
console.log(`Exported ${dep.GuardedVault}`);
